using System.Globalization;
using Microsoft.AspNetCore.Components.Web;
using Microsoft.AspNetCore.Components.WebAssembly.Hosting;
using PopcornTracker;
using PopcornTracker.Services;

var builder = WebAssemblyHostBuilder.CreateDefault(args);
builder.RootComponents.Add<App>("#app");
builder.RootComponents.Add<HeadOutlet>("head::after");

// Force French (Canada) formatting for dates in the whole app
var culture = new CultureInfo("fr-CA");
CultureInfo.DefaultThreadCurrentCulture = culture;
CultureInfo.DefaultThreadCurrentUICulture = culture;

// Read runtime settings from wwwroot/appsettings.json (generated by CI from GitHub secrets)
var config = new AppConfig
{
    SupabaseUrl = builder.Configuration["Supabase:Url"] ?? string.Empty,
    SupabaseAnonKey = builder.Configuration["Supabase:AnonKey"] ?? string.Empty,
    TmdbApiKey = builder.Configuration["Tmdb:ApiKey"] ?? string.Empty,
    CinemaName = builder.Configuration["Cinema:Name"] ?? "Le Clap Loretteville",
    CinemaScheduleUrl = builder.Configuration["Cinema:ScheduleUrl"] ?? string.Empty,
};

builder.Services.AddSingleton(config);
builder.Services.AddSingleton(new SupabaseProvider(await CreateSupabaseClientAsync(config)));
builder.Services.AddSingleton<TmdbService>();
builder.Services.AddScoped<OutingService>();

await builder.Build().RunAsync();

static async Task<Supabase.Client?> CreateSupabaseClientAsync(AppConfig config)
{
    if (string.IsNullOrWhiteSpace(config.SupabaseUrl) || string.IsNullOrWhiteSpace(config.SupabaseAnonKey))
    {
        return null;
    }

    var options = new Supabase.SupabaseOptions
    {
        // No login and no live updates for now: keep the client lightweight
        AutoConnectRealtime = false,
        AutoRefreshToken = false,
    };

    var client = new Supabase.Client(config.SupabaseUrl, config.SupabaseAnonKey, options);
    await client.InitializeAsync();
    return client;
}
